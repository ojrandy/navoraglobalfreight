// Builds src/styles/admin-shared.css: the rules from the admin stylesheets that the public site
// also uses (shared utility classes such as .text-emerald or .form-row-2). The public bundle loads
// only this file, in the place where all of the admin CSS used to load, and the admin console
// loads the full admin stylesheets from its own chunk (src/admin/styles.ts).
//
// A rule is kept when every class in one of its selectors appears in the public source code
// (everything in src/ outside src/admin/, plus index.html), or begins with a class prefix that
// public code builds at runtime (e.g. `status-${tone}`). Rules without any class are kept too.
// Re-run after changing admin CSS or the classes public pages use:  node scripts/admin-shared-css.mjs
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

function walk(dir, out = []) {
  for (const e of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const p = `${dir}/${e.name}`;
    if (e.isDirectory()) { if (p !== 'src/admin') walk(p, out); }
    else if (/\.(tsx?|html)$/.test(e.name)) out.push(p);
  }
  return out;
}

const publicSource = [...walk('src'), 'index.html'].map(read).join('\n');
const tokens = new Set(publicSource.match(/[A-Za-z0-9_-]+/g));
const prefixes = [...new Set([...publicSource.matchAll(/([A-Za-z0-9_-]+-)\$\{/g)].map((m) => m[1]))];
const isPublicClass = (c) => tokens.has(c) || prefixes.some((p) => c.startsWith(p));

function selectorIsPublic(selector) {
  const withoutNot = selector.replace(/:not\([^)]*\)/g, '');
  const classes = [...withoutNot.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((m) => m[1]);
  return classes.every(isPublicClass);
}

const files = [...read('src/admin/styles.ts').matchAll(/^import '\.\/(.+\.css)';/gm)]
  .map((m) => `src/admin/${m[1]}`)
  .filter((f) => !f.endsWith('/focus-ring.css')); // a copy of a global.css rule, see that file
const parts = [];
const stats = { kept: 0, dropped: 0 };

for (const file of files) {
  const ast = postcss.parse(read(file), { from: file });
  ast.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
    if (rule.selectors.some(selectorIsPublic)) stats.kept++;
    else { stats.dropped++; rule.remove(); }
  });
  ast.walkComments((c) => c.remove());
  // Drop emptied @media blocks, then keyframes nothing kept refers to.
  ast.walkAtRules((at) => { if (at.name === 'media' && !at.nodes?.length) at.remove(); });
  const used = ast.toString();
  ast.walkAtRules(/keyframes$/i, (at) => {
    const refs = used.split(at.toString()).join('');
    if (!new RegExp(`animation(-name)?\\s*:[^;]*\\b${at.params}\\b`).test(refs)) at.remove();
  });
  const css = ast.toString().replace(/\n{3,}/g, '\n\n').trim();
  if (css) parts.push(`/* ---- from ${file.replace('src/', '')} ---- */\n${css}`);
}

const header = `/* Generated by scripts/admin-shared-css.mjs. Do not edit by hand; edit the admin stylesheets
   and re-run the script. Admin CSS rules that public pages also use (see the script for how they
   are chosen). Loaded by the public bundle in the place where all of the admin CSS used to load. */`;
fs.writeFileSync(path.join(root, 'src/styles/admin-shared.css'), `${header}\n\n${parts.join('\n\n')}\n`);
console.log(`admin-shared.css: kept ${stats.kept} rules, dropped ${stats.dropped}`);
