// Regenerates src/assets/payment-icons/index.ts from the SVG files next to it (Simple Icons,
// one 24x24 path each). Run after adding or replacing an icon: node scripts/payment-icons.mjs
import fs from 'fs';
import path from 'path';

const dir = path.join(process.cwd(), 'src', 'assets', 'payment-icons');
const entries = fs.readdirSync(dir).filter((f) => f.endsWith('.svg')).sort().map((file) => {
  const svg = fs.readFileSync(path.join(dir, file), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)];
  if (paths.length !== 1 || /<(script|image|foreignObject)|href=|on\w+=/i.test(svg)) {
    throw new Error(`${file}: expected a single plain <path>`);
  }
  return `  ${JSON.stringify(file.replace(/\.svg$/, ''))}: ${JSON.stringify(paths[0][1])},`;
});

fs.writeFileSync(path.join(dir, 'index.ts'), [
  '// Generated by scripts/payment-icons.mjs from the SVG files in this folder. Do not edit by hand.',
  '// Brand marks from Simple Icons 16.34.0 (CC0); sources and guidelines: docs/update.md (C.2).',
  'export const PAYMENT_ICON_PATHS: Record<string, string> = {',
  ...entries,
  '};',
  '',
].join('\n'));
console.log(`Wrote ${entries.length} icons.`);
